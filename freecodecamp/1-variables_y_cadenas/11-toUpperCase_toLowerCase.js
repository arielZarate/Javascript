
/**
 * 
 Afortunadamente, JavaScript hace esto fácil con dos métodos integrados: toUpperCase() y toLowerCase().
 
 El método toUpperCase() convierte todos los caracteres a letras mayúsculas y devuelve una nueva cadena 
 con todos los caracteres en mayúsculas. Esto es útil cuando quieres enfatizar texto o crear consistencia en el formato de las cadenas.


 Por otro lado, el método toLowerCase() convierte todos los caracteres en una cadena a minúsculas. Esto es útil cuando necesitas estandarizar la entrada, como cuando comparas texto proporcionado por el usuario o haces verificaciones sin distinción de mayúscula
 */


 let greeting = "Hello, World!";
let uppercaseGreeting = greeting.toUpperCase();
console.log(uppercaseGreeting);  // "HELLO, WORLD!"


